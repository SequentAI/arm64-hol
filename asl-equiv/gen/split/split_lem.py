"""Split Sail's armv9.lem into Lem modules armv9_p1.. at the given line cuts.

Cuts come from cuts.py (0-based line numbers of `val` lines). Part k opens
the original imports plus every earlier part.
"""
import sys, pathlib

src, outdir, cutfile = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
lines = src.read_text().split('\n')
first_val = next(i for i, l in enumerate(lines) if l.startswith('val '))
header = [l for l in lines[:first_val] if l.startswith('open import')]
cuts = [first_val] + [int(c) for c in open(cutfile).read().split()] + [len(lines)]
n = len(cuts) - 1
for k in range(n):
    opens = header + [f'open import Armv9_p{j + 1}' for j in range(k)]
    text = [f'(*Generated by Sail from armv9; part {k + 1} of {n}.*)'] + opens + [''] + lines[cuts[k]:cuts[k + 1]]
    (outdir / f'armv9_p{k + 1}.lem').write_text('\n'.join(text) + '\n')
print(n, 'parts')
